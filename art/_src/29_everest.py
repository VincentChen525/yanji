"""29-everest：珠穆朗玛峰北壁，从绒布寺看。横幅。单位 km（示意）。
宽肩金字塔：左为长长的东北山脊（第一、二台阶 + 尖峰群），右为西山脊；上部横贯的黄色岩带（两道线）；
诺顿大岩沟与霍恩宾岩沟两道雪槽；峰顶向右拖出一缕旗云；山脚绒布冰川。"""
import sys, random, math
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull, glacier_marks
cv = Canvas("横", seed=29, sx=0.55)
rnd = random.Random(29)
S = (0.3, 1.3)
left = ridge([S, (0.18, 1.18), (0.05, 1.04), (-0.05, 0.94), (-0.12, 0.89), (-0.16, 0.85), (-0.35, 0.82), (-0.55, 0.8), (-0.6, 0.77), (-0.9, 0.73),
              (-1.25, 0.67), (-1.45, 0.66), (-1.52, 0.69), (-1.6, 0.64), (-1.7, 0.67), (-1.78, 0.62), (-1.95, 0.6),
              (-2.3, 0.5), (-2.7, 0.38), (-3.1, 0.22), (-3.4, 0.08), (-3.5, 0.0)], 0.012, 1)
right = ridge([S, (0.45, 1.16), (0.62, 1.0), (0.75, 0.9), (0.9, 0.76), (1.2, 0.64), (1.5, 0.55), (1.85, 0.45), (2.2, 0.35), (2.6, 0.22), (3.0, 0.09), (3.2, 0.0)], 0.015, 2)
sil = list(reversed(left)) + right[1:]
SKY = sky(sil)
cv.line(sil, OUTER)
cv.line([(-3.6, 0), (3.4, 0)], OUTER)
# 黄色岩带：上部横贯北壁的两道线
yb1 = ridge([(-0.1, 0.98), (0.2, 1.06), (0.5, 1.04), (0.75, 0.96)], 0.02, 3)
yb2 = ridge([(-0.25, 0.9), (0.15, 0.97), (0.5, 0.95), (0.9, 0.86)], 0.02, 4)
cv.line(yb1, INNER, hide=[SKY]); cv.line(yb2, INNER, hide=[SKY])
# 岩带内的短竖纹
for i in range(11):
    x = -0.05 + i * 0.075
    zt = 1.0 + 0.06 * math.sin((x + 0.1) / 0.85 * math.pi) - 0.03
    cv.line([(x, zt), (x - 0.01, zt - 0.06)], INNER, hide=[SKY])
# 两道大雪槽（双线）
for pts, w, sd in [([(0.4, 1.2), (0.36, 0.95), (0.25, 0.7), (0.12, 0.45), (0.05, 0.28)], 0.022, 5),
                   ([(0.22, 1.2), (0.08, 0.98), (-0.08, 0.72), (-0.2, 0.48), (-0.28, 0.3)], 0.02, 6)]:
    c = ridge(pts, 0.03, sd)
    cv.line([(x - w, z) for x, z in c], INNER, hide=[SKY]); cv.line([(x + w, z) for x, z in c], INNER, hide=[SKY])
# 北壁下部：几道岩肋与雪坡分界
for pts, sd in [([(-0.9, 0.72), (-0.8, 0.5), (-0.85, 0.3)], 7), ([(-1.5, 0.64), (-1.4, 0.45), (-1.5, 0.28)], 8),
                ([(0.75, 0.84), (0.7, 0.6), (0.8, 0.35)], 9), ([(1.3, 0.6), (1.2, 0.42), (1.3, 0.25)], 10),
                ([(-0.5, 0.78), (-0.55, 0.55), (-0.5, 0.35)], 11)]:
    cv.line(ridge(pts, 0.04, sd), INNER, hide=[SKY])
# 山脚冰川
gl = ridge([(-2.9, 0.2), (-1.5, 0.27), (0.0, 0.24), (1.5, 0.27), (2.6, 0.18)], 0.02, 12)
cv.line(gl, INNER, hide=[SKY])
glacier_marks(cv, -2.6, 2.4, 0.24, 0.04, seed=29, density=1.8)
# 旗云：从峰顶向右拖出的几道渐细波线
for k, (dz, ln) in enumerate([(0.0, 2.4), (-0.05, 1.8), (0.04, 1.3)]):
    pts = [(S[0] + 0.04 + ln * i / 14, S[1] + dz + 0.03 * math.sin(i * 0.9 + k) * (i / 14) - 0.1 * (i / 14)) for i in range(15)]
    cv.smooth(pts, INNER, n=4)
cv.save(sys.argv[1])
