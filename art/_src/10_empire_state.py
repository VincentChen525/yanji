"""10-empire-state：帝国大厦正立面（第五大道）。竖幅。单位米。屋顶 381m，天线顶 443m。"""
import sys
from lineart import Canvas, OUTER, INNER
cv = Canvas("竖", seed=10)
L = cv.line
# 分段：(z0, z1, 半宽)
blocks = [(0, 24, 58), (24, 78, 46), (78, 96, 38), (96, 262, 31), (262, 318, 22)]
for z0, z1, w in blocks:
    L([(-w, z0), (-w, z1)], OUTER); L([(w, z0), (w, z1)], OUTER)
    L([(-w, z1), (w, z1)], OUTER)
L([(-64, 0), (64, 0)], OUTER)
# 竖向窗带
for z0, z1, w in blocks:
    step = 4.6 if w < 40 else 5.8
    n = int(2 * w / step)
    for i in range(1, n):
        x = -w + 2 * w * i / n
        L([(x, z0 + 3), (x, z1 - 2)])
# 塔身中央凸出的一条竖向壁柱（帝国大厦正面的中轴）
for x in (-6.5, 6.5):
    L([(x, 96), (x, 324)], OUTER)
L([(-6.5, 324), (6.5, 324)], OUTER)
# 首层入口
cv.rect(-9, 0, 9, 14, OUTER); L([(-9, 10), (9, 10)])
# 86 层观景台 + 系泊塔（逐级收小的圆筒）+ 圆顶
L([(-24, 318), (-24, 322), (24, 322), (24, 318)], OUTER)
tiers = [(322, 336, 13.5), (336, 352, 11), (352, 362, 9)]
for z0, z1, w in tiers:
    L([(-w, z0), (-w, z1), (w, z1), (w, z0)], OUTER)
    for i in range(1, 6):
        x = -w + 2 * w * i / 6
        L([(x, z0 + 1.5), (x, z1 - 1.5)])
cv.smooth([(-9, 362), (-8.2, 368), (-6, 373), (-3, 376), (0, 377)], OUTER, n=6)
cv.smooth([(9, 362), (8.2, 368), (6, 373), (3, 376), (0, 377)], OUTER, n=6)
for x in (-4.5, 0, 4.5):
    L([(x * 1.4, 363), (x * 0.5, 375.5)])
# 天线
L([(-2.2, 377), (-1.4, 400), (-0.6, 400), (-0.4, 443), (0.4, 443), (0.6, 400), (1.4, 400), (2.2, 377)], OUTER)
cv.save(sys.argv[1])
