"""16-table-mountain：桌山，从桌湾对岸看。横幅。单位 km，竖向夸张 1.8 倍（实景约 10:1，太扁无法辨认）。
左：魔鬼峰（尖）；中：平顶台地 + 台缘下的崖壁带；右：狮子头（锥形）与信号山。台地上覆一条“桌布云”。"""
import sys
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull
cv = Canvas("横", seed=16)
VEX = 1.8
def V(pts): return [(x, z * VEX) for x, z in pts]

sil = V([(-6.8, 0), (-5.8, 0.12)] + ridge([(-5.8, 0.12), (-4.95, 0.62), (-4.3, 1.0)], 0.04, 1)[1:]
        + ridge([(-4.3, 1.0), (-3.75, 0.8), (-3.25, 1.06)], 0.03, 2)[1:]
        + [(-2.7, 1.075), (-2.2, 1.08), (-1.4, 1.075), (-0.6, 1.085), (0.4, 1.08), (1.25, 1.075)]
        + ridge([(1.3, 1.06), (1.55, 0.8), (1.9, 0.55), (2.6, 0.32)], 0.04, 3)[1:]
        + ridge([(2.6, 0.32), (3.4, 0.5), (3.95, 0.67)], 0.02, 4)[1:]
        + [(4.15, 0.665), (4.35, 0.6)] + ridge([(4.35, 0.6), (4.9, 0.35), (5.6, 0.33), (6.4, 0.12)], 0.03, 5)[1:] + [(7.0, 0)])
SKY = sky(sil)
# 桌布云：盖在台地上，云边垂挂到崖壁带上方
cloud_top = V(catmull([(-3.0, 1.06), (-2.7, 1.13), (-2.3, 1.12), (-1.9, 1.15), (-1.4, 1.13), (-0.9, 1.16), (-0.4, 1.14),
                       (0.1, 1.16), (0.6, 1.13), (1.05, 1.12), (1.32, 1.04)], 6))
cloud_bot = V(catmull([(1.32, 1.04), (1.1, 0.98), (0.8, 1.0), (0.55, 0.95), (0.3, 0.99), (-0.1, 0.96), (-0.4, 1.0),
                       (-0.8, 0.94), (-1.2, 0.99), (-1.6, 0.97), (-2.0, 1.0), (-2.4, 0.95), (-2.75, 1.0), (-3.0, 1.06)], 6))
CLOUD = cloud_top + cloud_bot
cv.line(sil, OUTER, hide=[CLOUD])
cv.line(cloud_top, OUTER); cv.line(cloud_bot, INNER)
# 台缘下崖壁带：下沿 + 竖向扶壁裂隙
band = V(ridge([(-3.1, 0.8), (-1.5, 0.78), (0.0, 0.8), (1.25, 0.77)], 0.02, 6))
cv.line(band, INNER, hide=[CLOUD])
import random
rnd = random.Random(16)
x = -3.0
while x < 1.2:
    z1 = 1.07 * VEX; z0 = (0.79 + rnd.uniform(-0.02, 0.02)) * VEX
    cv.line([(x, z1), (x + rnd.uniform(-0.03, 0.03), z0)], INNER, hide=[CLOUD, SKY])
    x += rnd.uniform(0.12, 0.26)
# 台地下坡：几道冲沟与山脊线
for x0, x1 in [(-2.4, -2.7), (-1.6, -1.75), (-0.6, -0.55), (0.3, 0.45), (1.0, 1.35)]:
    cv.line(V(ridge([(x0, 0.77), ((x0 + x1) / 2, 0.45), (x1, 0.12)], 0.05, int(x0 * 10) + 50)), INNER, hide=[SKY])
# 魔鬼峰：一道主脊
cv.line(V(ridge([(-4.3, 1.0), (-4.05, 0.6), (-3.7, 0.25)], 0.04, 7)), INNER, hide=[SKY])
# 狮子头：顶部岩冠的层理
for z in (0.6, 0.55):
    cv.line(V([(3.72, z), (4.25, z - 0.01)]), INNER, hide=[SKY])
cv.line(V(ridge([(4.05, 0.66), (3.9, 0.4), (3.6, 0.15)], 0.04, 8)), INNER, hide=[SKY])
cv.line([(-7.2, 0), (7.4, 0)], OUTER)
cv.save(sys.argv[1])
