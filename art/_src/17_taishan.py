"""17-taishan：泰山。横幅。单位 km（示意）。
厚重宽阔、顶部浑圆；十八盘石阶沿山谷直上鞍部的南天门；岱顶有小庙顶；坡上几株松。"""
import sys, math
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull, pine_flat
cv = Canvas("横", seed=17)
GATE = (-0.62, 1.82)
sil = ridge([(-4.2, 0), (-3.4, 0.5), (-2.8, 0.95), (-2.2, 1.3), (-1.75, 1.62)], 0.06, 1) + \
      ridge([(-1.75, 1.62), (-1.35, 2.0), (-1.15, 1.95), (-0.95, 1.88), GATE], 0.04, 2)[1:] + \
      catmull([GATE, (-0.3, 2.05), (0.1, 2.28), (0.5, 2.36), (0.9, 2.3), (1.25, 2.1)], 6)[1:] + \
      ridge([(1.25, 2.1), (1.6, 1.85), (2.0, 1.55), (2.5, 1.2), (3.0, 0.85), (3.6, 0.45), (4.3, 0)], 0.05, 3)[1:]
SKY = sky(sil)
# 南天门：台基 + 门洞 + 歇山顶
gx, gz = GATE
gate_poly = [(gx - 0.13, gz - 0.06), (gx + 0.13, gz - 0.06), (gx + 0.13, gz + 0.1), (gx + 0.17, gz + 0.12),
             (gx + 0.06, gz + 0.2), (gx - 0.06, gz + 0.2), (gx - 0.17, gz + 0.12), (gx - 0.13, gz + 0.1)]
# 岱顶小庙
temples = [(0.25, 2.31, 0.12), (0.68, 2.345, 0.09)]
temple_polys = [[(x - w, z - 0.02), (x + w, z - 0.02), (x + w, z + 0.06), (x + w * 1.3, z + 0.07), (x, z + 0.13),
                 (x - w * 1.3, z + 0.07), (x - w, z + 0.06)] for x, z, w in temples]
# 松树
pines = [(-2.25, 1.24, 0.5, -1, 1), (1.9, 1.62, 0.46, 1, 3), (-1.3, 1.97, 0.36, 1, 5)]
pine_lines, pine_polys = [], []
for x, z, h, s, sd in pines:
    l, p = pine_flat(x, z, h, s, sd)
    pine_lines += l; pine_polys += p
FRONT = [gate_poly] + temple_polys + pine_polys
cv.line(sil, OUTER, hide=FRONT)
cv.line([(-4.5, 0), (4.6, 0)], OUTER)
# 门
L = cv.line
L([(gx - 0.13, gz - 0.06), (gx - 0.13, gz + 0.1), (gx + 0.13, gz + 0.1), (gx + 0.13, gz - 0.06)], OUTER)
L(catmull([(gx - 0.04, gz - 0.06), (gx - 0.04, gz + 0.02), (gx, gz + 0.05), (gx + 0.04, gz + 0.02), (gx + 0.04, gz - 0.06)], 4))
L([(gx - 0.17, gz + 0.12), (gx - 0.13, gz + 0.1), (gx + 0.13, gz + 0.1), (gx + 0.17, gz + 0.12)], OUTER)
L(catmull([(gx - 0.17, gz + 0.12), (gx - 0.1, gz + 0.15), (gx - 0.06, gz + 0.2), (gx + 0.06, gz + 0.2), (gx + 0.1, gz + 0.15), (gx + 0.17, gz + 0.12)], 4), OUTER)
L([(gx - 0.13, gz + 0.04), (gx + 0.13, gz + 0.04)])
for (x, z, w), p in zip(temples, temple_polys):
    L([(x - w, z - 0.02), (x - w, z + 0.06), (x + w, z + 0.06), (x + w, z - 0.02)], OUTER)
    L(catmull([(x - w * 1.3, z + 0.07), (x - w * 0.5, z + 0.1), (x, z + 0.13), (x + w * 0.5, z + 0.1), (x + w * 1.3, z + 0.07)], 4), OUTER)
    L([(x - w * 1.3, z + 0.07), (x + w * 1.3, z + 0.07)])
# 十八盘：两条石阶边线 + 横档，越往上越陡越密
path = catmull([(gx, gz - 0.06), (-0.66, 1.5), (-0.78, 1.2), (-0.72, 0.9), (-0.85, 0.6), (-0.9, 0.3), (-1.05, 0.02)], 10)
for off in (-0.022, 0.022):
    L([(x + off, z) for x, z in path], INNER, hide=FRONT)
for i in range(0, len(path) - 1, 2):
    x, z = path[i]
    L([(x - 0.022, z), (x + 0.022, z)], INNER, hide=FRONT)
# 山谷两侧的岩壁
L(ridge([(-0.85, 1.8), (-1.0, 1.4), (-1.05, 1.0), (-1.15, 0.6), (-1.3, 0.25)], 0.05, 6), INNER, hide=[SKY] + FRONT)
L(ridge([(-0.4, 1.9), (-0.5, 1.5), (-0.55, 1.1), (-0.65, 0.7), (-0.7, 0.35)], 0.05, 7), INNER, hide=[SKY] + FRONT)
# 从岱顶放射下来的几道山脊（支脉）
for pts, sd in [([(0.3, 2.3), (0.2, 1.8), (0.3, 1.3), (0.15, 0.8), (0.25, 0.3)], 8),
                ([(0.95, 2.25), (1.1, 1.75), (1.05, 1.3), (1.3, 0.8), (1.4, 0.3)], 9),
                ([(-1.4, 1.95), (-1.6, 1.5), (-1.55, 1.1), (-1.8, 0.6), (-1.9, 0.2)], 10),
                ([(2.0, 1.5), (2.2, 1.1), (2.15, 0.7), (2.4, 0.3)], 11),
                ([(-2.6, 1.05), (-2.7, 0.7), (-2.6, 0.35)], 12)]:
    L(ridge(pts, 0.05, sd), INNER, hide=[SKY] + FRONT)
# 花岗岩层状岩台：近顶部几道短横向岩缝
import random
rnd = random.Random(17)
for x0, z0, ln in [(-0.2, 1.95, 0.35), (0.45, 2.05, 0.4), (-1.25, 1.75, 0.3), (1.25, 1.85, 0.3), (0.6, 1.6, 0.35),
                   (-0.15, 1.45, 0.3), (1.5, 1.4, 0.3), (-1.75, 1.3, 0.25), (0.75, 1.1, 0.3), (-0.3, 0.95, 0.25),
                   (1.75, 0.95, 0.3), (-2.2, 0.75, 0.25), (2.6, 0.7, 0.25), (0.4, 0.6, 0.25)]:
    L(ridge([(x0, z0), (x0 + ln / 2, z0 + rnd.uniform(-0.03, 0.03)), (x0 + ln, z0 - 0.05)], 0.08, int(x0 * 100) + 99),
      INNER, hide=[SKY] + FRONT)
for l in pine_lines:
    L(l, INNER)
for p in pine_polys:
    L(p, INNER, closed=True)
cv.save(sys.argv[1])
