"""13-cn-tower：多伦多电视塔。竖幅。单位米。总高 553m。
三翼 Y 形底座外撇，混凝土塔身收分，约 2/3 高处甜甜圈形主观景舱，上方 SkyPod 小环，长天线。"""
import math, sys
from lineart import Canvas, OUTER, INNER
cv = Canvas("竖", seed=13)
L, S = cv.line, cv.smooth


def hw(z):  # 塔身半宽：底部三翼外撇，往上收成细筒
    return 6.2 + 15.5 * math.exp(-z / 55.0) + 3.0 * (1 - z / 446)


P0, P1 = 328.0, 372.0
for s in (-1, 1):
    L([(s * hw(z), z) for z in range(0, int(P0) + 1, 4)], OUTER)
    L([(s * hw(z), z) for z in range(int(P1), 441, 4)], OUTER)
    # 翼的中线：正面看到一片翼朝向观者
    L([(s * 3.0 * (1 - z / 330.0) + s * 0.6, z) for z in range(0, 300, 6)])
L([(-30, 0), (30, 0)], OUTER)
# 主观景舱
S([(-hw(P0), P0), (-13, P0 + 6), (-21, P0 + 13), (-22, P0 + 18)], OUTER, n=6)
S([(hw(P0), P0), (13, P0 + 6), (21, P0 + 13), (22, P0 + 18)], OUTER, n=6)
L([(-22, P0 + 18), (-22.5, P0 + 30), (22.5, P0 + 30), (22, P0 + 18)], OUTER)
L([(-22, P0 + 18), (22, P0 + 18)])
L([(-22.3, P0 + 24), (22.3, P0 + 24)])
for i in range(1, 12):
    x = -22 + 44 * i / 12
    L([(x, P0 + 18.5), (x, P0 + 23.5)])
S([(-22.5, P0 + 30), (-17, P0 + 37), (-9, P0 + 41), (-hw(P1), P1)], OUTER, n=6)
S([(22.5, P0 + 30), (17, P0 + 37), (9, P0 + 41), (hw(P1), P1)], OUTER, n=6)
# 白色外环
cv.smooth([(-25.5, P0 + 14), (-26.5, P0 + 21), (-25.5, P0 + 28)], OUTER, n=5)
cv.smooth([(25.5, P0 + 14), (26.5, P0 + 21), (25.5, P0 + 28)], OUTER, n=5)
L([(-25.5, P0 + 14), (-22.0, P0 + 15)]); L([(25.5, P0 + 14), (22.0, P0 + 15)])
L([(-25.5, P0 + 28), (-22.5, P0 + 29)]); L([(25.5, P0 + 28), (22.5, P0 + 29)])
# SkyPod
L([(-hw(440), 440), (-8.5, 443), (-8.5, 451), (-4.5, 455), (4.5, 455), (8.5, 451), (8.5, 443), (hw(440), 440)], OUTER)
L([(-8.5, 447), (8.5, 447)])
# 天线
L([(-3.6, 455), (-3.0, 490), (-2.0, 490), (-1.2, 530), (-0.6, 553), (0.6, 553), (1.2, 530), (2.0, 490), (3.0, 490), (3.6, 455)], OUTER)
L([(-1.2, 530), (1.2, 530)])
cv.save(sys.argv[1])
