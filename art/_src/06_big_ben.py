"""06-big-ben：伊丽莎白塔正立面。竖幅。单位米。高 96m，方 12m。"""
import math, sys
from lineart import Canvas, OUTER, INNER
cv = Canvas("竖", seed=6)
L, S = cv.line, cv.smooth
W = 6.0
# 塔身
L([(-W - 0.4, 0), (-W, 1.5), (-W, 55)], OUTER); L([(W + 0.4, 0), (W, 1.5), (W, 55)], OUTER)
L([(-W - 3, 0), (W + 3, 0)], OUTER)
for x in (-4.2, 4.2):            # 转角扶壁
    L([(x, 1.5), (x, 55)])
for z in range(8, 55, 8):         # 分层腰线
    L([(-W, z), (W, z)])
    for x in (-2.4, -0.8, 0.8, 2.4):   # 竖向窗格
        L([(x, z - 6.2), (x, z - 1.2)])
    S([(-3.2, z - 1.2), (-2.4, z - 0.4), (-1.6, z - 1.2)], n=4); S([(1.6, z - 1.2), (2.4, z - 0.4), (3.2, z - 1.2)], n=4)
    S([(-1.6, z - 1.2), (-0.8, z - 0.4), (0, z - 1.2)], n=4); S([(0, z - 1.2), (0.8, z - 0.4), (1.6, z - 1.2)], n=4)
# 钟面层（略宽）
L([(-W - 0.6, 55), (W + 0.6, 55)], OUTER)
L([(-W - 0.6, 55), (-W - 0.6, 70.5)], OUTER); L([(W + 0.6, 55), (W + 0.6, 70.5)], OUTER)
cv.rect(-5.6, 56.5, 5.6, 69.0)
cv.circle(0, 62.75, 4.7, OUTER)
cv.circle(0, 62.75, 3.9)
for i in range(12):
    a = math.radians(i * 30)
    L([(3.9 * math.cos(a), 62.75 + 3.9 * math.sin(a)), (4.5 * math.cos(a), 62.75 + 4.5 * math.sin(a))])
L([(0, 62.75), (2.0, 64.6)], OUTER); L([(0, 62.75), (0.3, 66.0)], OUTER)   # 指针
for sx in (-1, 1):  # 钟面四角小圆
    for z in (57.8, 67.7):
        cv.circle(sx * 4.6, z, 0.55)
L([(-W - 0.9, 70.5), (W + 0.9, 70.5)], OUTER)
# 钟楼层：三个尖拱百叶
L([(-W, 70.5), (-W, 78)], OUTER); L([(W, 70.5), (W, 78)], OUTER)
for x in (-3.3, 0, 3.3):
    L([(x - 1.2, 71.5), (x - 1.2, 75.2)] + [(x - 1.2 + 1.2 * (1 - math.cos(math.pi / 2 * i / 5)), 75.2 + 1.6 * math.sin(math.pi / 2 * i / 5)) for i in range(6)]
      + [(x + 1.2 - 1.2 * (1 - math.cos(math.pi / 2 * i / 5)), 75.2 + 1.6 * math.sin(math.pi / 2 * i / 5)) for i in range(5, -1, -1)] + [(x + 1.2, 71.5)])
L([(-W - 0.5, 78), (W + 0.5, 78)], OUTER)
# 陡峭的铁皮尖顶 + 中段灯笼层 + 四角小尖塔
L([(-W, 78), (-3.6, 86), (-3.6, 89), (-1.8, 94), (0, 96.5), (1.8, 94), (3.6, 89), (3.6, 86), (W, 78)], OUTER)
L([(-3.6, 86), (3.6, 86)]); L([(-3.6, 89), (3.6, 89)])
for x in (-2.2, -0.7, 0.7, 2.2):
    L([(x, 86.4), (x, 88.6)])
L([(-2.6, 80.5), (-1.6, 84.5), (-0.6, 80.5)]); L([(0.6, 80.5), (1.6, 84.5), (2.6, 80.5)])
for sx in (-1, 1):
    L([(sx * 6.0, 78), (sx * 6.0, 81.5), (sx * 5.6, 84), (sx * 5.2, 81.5), (sx * 5.2, 78)], INNER)
L([(0, 96.5), (0, 98.5)], OUTER)
cv.save(sys.argv[1])
