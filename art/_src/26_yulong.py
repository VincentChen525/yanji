"""26-yulong：玉龙雪山。横幅。单位 km（示意）。
一长列锯齿状尖峰如龙脊；近中央最高的扇子陡主峰（扇形宽顶）；峰面有竖向的冰槽/岩槽纹；主峰下一条小冰川。"""
import sys, random
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull
cv = Canvas("横", seed=26, sx=0.62)
rnd = random.Random(26)
peaks = [(-3.0, 0.35), (-2.75, 0.7), (-2.6, 0.58), (-2.4, 0.88), (-2.25, 0.76), (-2.05, 1.02), (-1.88, 0.9), (-1.65, 1.12),
         (-1.48, 1.02), (-1.25, 1.2), (-1.08, 1.12), (-0.88, 1.3), (-0.72, 1.42), (-0.55, 1.47), (-0.38, 1.43), (-0.22, 1.24),
         (0.0, 1.3), (0.15, 1.16), (0.38, 1.26), (0.55, 1.1), (0.78, 1.18), (0.95, 1.02), (1.18, 1.1), (1.38, 0.94),
         (1.6, 0.98), (1.85, 0.8), (2.1, 0.84), (2.4, 0.6), (2.7, 0.46), (3.1, 0.22), (3.4, 0.0)]
sil = [(-3.4, 0.0)] + ridge(peaks, 0.04, 1)
SKY = sky(sil)
cv.line(sil, OUTER)
cv.line([(-3.5, 0), (3.5, 0)], OUTER)
# 冰槽：从每个尖峰向下的几道近竖线
tops = [p for i, p in enumerate(peaks[1:-3]) if p[1] > peaks[i][1]]
for x, z in tops:
    for k in range(3):
        dx = rnd.uniform(-0.12, 0.12)
        ln = rnd.uniform(0.2, 0.42)
        cv.line(ridge([(x + dx * 0.3, z - 0.04), (x + dx, z - ln)], 0.05, int(x * 100) + k), INNER, hide=[SKY])
# 主峰扇面：宽顶下的扇形纹
for k in range(6):
    xt = -0.86 + k * 0.1
    cv.line([(xt, 1.38 if 0 < k < 5 else 1.28), (-0.55 + (xt + 0.55) * 1.6, 0.95)], INNER, hide=[SKY])
# 雪线：山腰一条起伏的线（以下为岩坡/林带）
snow = ridge([(-2.9, 0.42), (-2.0, 0.6), (-1.2, 0.72), (-0.5, 0.8), (0.3, 0.75), (1.1, 0.68), (1.9, 0.55), (2.7, 0.38)], 0.03, 3)
cv.line(snow, INNER, hide=[SKY])
# 山麓：前方一道较低的林坡山脊
cv.line(ridge([(-3.2, 0.12), (-2.0, 0.28), (-0.8, 0.32), (0.6, 0.3), (1.8, 0.26), (3.1, 0.1)], 0.03, 4), INNER, hide=[SKY])
# 主峰下小冰川
gl_l = catmull([(-0.7, 0.85), (-0.68, 0.7), (-0.62, 0.55), (-0.58, 0.42)], 4)
gl_r = catmull([(-0.42, 0.85), (-0.45, 0.7), (-0.47, 0.55), (-0.5, 0.42)], 4)
cv.line(gl_l, INNER); cv.line(gl_r, INNER)
cv.smooth([(-0.58, 0.42), (-0.54, 0.39), (-0.5, 0.42)], INNER, n=3)
for z in (0.75, 0.64, 0.53):
    cv.smooth([(-0.68 + (0.85 - z) * 0.2, z), (-0.56, z - 0.02), (-0.44 - (0.85 - z) * 0.12, z)], INNER, n=3)
cv.save(sys.argv[1])
