"""19-huashan：华山西峰。方幅。单位 km（示意）。
光秃的整块白色花岗岩：右侧刀削般的垂直绝壁，正面平滑带长竖裂缝；左侧刀刃般的窄脊通向峰顶；顶上几株小松和一座小庙。"""
import sys, random
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull, pine_flat
cv = Canvas("方", seed=19)
rnd = random.Random(19)
ridge_l = ridge([(-1.0, 0.0), (-0.92, 0.25), (-0.75, 0.48), (-0.6, 0.66), (-0.45, 0.84), (-0.3, 1.0), (-0.18, 1.18)], 0.035, 1)
top = catmull([(-0.18, 1.18), (-0.08, 1.36), (0.08, 1.47), (0.25, 1.52), (0.42, 1.5), (0.52, 1.46)], 6)
cliff = ridge([(0.52, 1.46), (0.56, 1.25), (0.58, 0.9), (0.6, 0.5), (0.62, 0.0)], 0.012, 2)
sil = ridge_l + top[1:] + cliff[1:]
SKY = sky(sil)
temple = (0.3, 1.515)
tp = [(0.24, 1.49), (0.36, 1.49), (0.36, 1.56), (0.39, 1.57), (0.3, 1.62), (0.21, 1.57), (0.24, 1.56)]
pl, pp = [], []
for x, z, h, s, sd in [(0.02, 1.43, 0.13, -1, 1), (0.13, 1.47, 0.1, 1, 2), (0.46, 1.48, 0.11, 1, 3), (-0.12, 1.3, 0.09, -1, 4)]:
    l, p = pine_flat(x, z, h, s, sd); pl += l; pp += p
FRONT = [tp] + pp
cv.line(sil, OUTER, hide=FRONT)
cv.line([(-1.1, 0), (0.85, 0)], OUTER)
# 正面两个面的交棱：一条从峰顶直落的竖线（“刀削”面的左缘）
edge = ridge([(0.12, 1.46), (0.15, 1.1), (0.14, 0.7), (0.17, 0.3), (0.18, 0.0)], 0.01, 3)
cv.line(edge, OUTER, hide=FRONT)
# 刀削面：少量很长的竖向条纹
for x in (0.26, 0.36, 0.45, 0.53):
    z0 = 1.45 - rnd.uniform(0.02, 0.12)
    cv.line(ridge([(x, z0), (x + 0.01, z0 - 0.6), (x + 0.02, rnd.uniform(0.05, 0.4))], 0.008, int(x * 100)), INNER, hide=[SKY] + FRONT)
# 左侧裂隙面：更多弯折的竖裂缝
for x in (-0.05, -0.15, -0.28, -0.4, -0.55, -0.7, 0.04):
    z0 = min(1.35, 1.12 + x * 0.9) - rnd.uniform(0.02, 0.1)
    cv.line(ridge([(x, z0), (x - 0.03, z0 * 0.55), (x - 0.02, rnd.uniform(0.02, 0.2))], 0.03, int(-x * 100) + 50), INNER, hide=[SKY] + FRONT)
# 刀刃脊：脊线下方一条紧贴的平行线 + 几处台阶
cv.line([(x + 0.04, z - 0.035) for x, z in ridge_l[8:]], INNER, hide=[SKY] + FRONT)
# 小庙
L = cv.line
L([(0.24, 1.49), (0.24, 1.56), (0.36, 1.56), (0.36, 1.49)], OUTER)
L(catmull([(0.21, 1.57), (0.26, 1.59), (0.3, 1.62), (0.34, 1.59), (0.39, 1.57)], 4), OUTER)
L([(0.21, 1.57), (0.39, 1.57)])
L([(0.28, 1.49), (0.28, 1.535), (0.32, 1.535), (0.32, 1.49)])
for ln in pl: L(ln, INNER)
for q in pp: L(q, INNER, closed=True)
cv.save(sys.argv[1])
