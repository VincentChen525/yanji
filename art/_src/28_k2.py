"""28-k2：乔戈里峰，从协和广场看。方幅。单位 km（示意）。
比珠峰陡峭尖锐得多、近乎对称的岩冰金字塔；右侧山脊中段有明显的“肩”；面上有岩肋与冰槽、一道悬冰川带；山脚冰川。"""
import sys, random
from lineart import Canvas, OUTER, INNER, ridge, sky, catmull, glacier_marks
cv = Canvas("方", seed=28, sx=0.75)
rnd = random.Random(28)
left = ridge([(0.0, 1.0), (-0.06, 0.95), (-0.15, 0.85), (-0.27, 0.71), (-0.4, 0.57), (-0.55, 0.42), (-0.7, 0.28), (-0.86, 0.14), (-1.0, 0.04)], 0.02, 1)
right = ridge([(0.0, 1.0), (0.06, 0.95), (0.15, 0.84), (0.26, 0.71), (0.34, 0.64), (0.42, 0.61), (0.5, 0.59), (0.57, 0.55),
               (0.67, 0.42), (0.8, 0.28), (0.93, 0.14), (1.05, 0.04)], 0.02, 2)
sil = list(reversed(left)) + right[1:]
SKY = sky(sil)
cv.line(sil, OUTER)
# 岩肋：从峰顶附近放射向下
for pts, sd, w in [([(0.0, 0.98), (-0.06, 0.75), (-0.12, 0.5), (-0.2, 0.22)], 3, OUTER),
                   ([(0.02, 0.96), (0.1, 0.72), (0.16, 0.48), (0.22, 0.2)], 4, INNER),
                   ([(-0.08, 0.92), (-0.25, 0.6), (-0.4, 0.3)], 5, INNER),
                   ([(0.45, 0.6), (0.44, 0.42), (0.47, 0.22)], 6, INNER),
                   ([(-0.3, 0.68), (-0.45, 0.45), (-0.6, 0.22)], 7, INNER)]:
    cv.line(ridge(pts, 0.04, sd), w, hide=[SKY])
# 瓶颈处的悬冰川带
cv.line(ridge([(-0.14, 0.84), (-0.02, 0.82), (0.1, 0.83), (0.18, 0.81)], 0.06, 8), INNER, hide=[SKY])
for x in (-0.1, -0.03, 0.04, 0.11):
    cv.line([(x, 0.83), (x + 0.005, 0.8)], INNER)
# 冰槽：顺坡的细长线，成对出现
for x0, z0, dx, sd in [(-0.22, 0.7, -0.12, 9), (0.24, 0.68, 0.1, 10), (-0.02, 0.62, -0.03, 11), (0.6, 0.5, 0.08, 12), (-0.5, 0.42, -0.1, 13)]:
    for k in (0, 1):
        x = x0 + k * 0.045
        cv.line(ridge([(x, z0), (x + dx, z0 - 0.3)], 0.04, sd * 3 + k), INNER, hide=[SKY])
# 山脚冰川：上缘 + 冰塔林的短竖线 + 冰碛条纹
gl = ridge([(-0.95, 0.12), (-0.5, 0.17), (0.0, 0.14), (0.5, 0.18), (1.0, 0.12)], 0.02, 14)
cv.line(gl, INNER, hide=[SKY])
glacier_marks(cv, -0.85, 0.9, 0.15, 0.05, seed=28, density=1.3)
cv.line(ridge([(-1.1, 0.04), (0.0, 0.05), (1.15, 0.04)], 0.01, 15), INNER)
cv.line([(-1.15, 0), (1.2, 0)], OUTER)
cv.save(sys.argv[1])
