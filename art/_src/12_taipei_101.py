"""12-taipei-101：台北 101 正立面。竖幅。单位米。屋顶 449m，塔尖 508m。
收分的基座 + 8 节外撇的竹节/宝塔式塔段 + 古钱币装饰 + 阶梯塔冠 + 塔尖。"""
import math, sys
from lineart import Canvas, OUTER, INNER
cv = Canvas("竖", seed=12)
L = cv.line
# 基座：上窄下宽
L([(-31, 0), (-24.5, 92), (24.5, 92), (31, 0)], OUTER)
L([(-36, 0), (36, 0)], OUTER)
for z in (18, 36, 54, 72):
    w = 31 - 6.5 * z / 92
    L([(-w, z), (w, z)])
for x in (-14, -7, 0, 7, 14):
    L([(x * 1.18, 2), (x, 90)])
# 古钱币
cv.circle(0, 98, 4.2, OUTER); cv.rect(-1.3, 96.7, 1.3, 99.3)
# 8 节塔段，每节下窄上宽
z = 92.0
H = 36.0
for k in range(8):
    z0, z1 = z, z + H
    L([(-22.5, z0), (-27.5, z1), (27.5, z1), (22.5, z0)], OUTER)
    for f in (0.3, 0.6):
        w = 22.5 + 5 * f
        L([(-w, z0 + H * f), (w, z0 + H * f)])
    for x in (-13, -6.5, 0, 6.5, 13):
        L([(x, z0 + 1.5 if k else z0 + 8), (x * 1.18, z1 - 1.5)])
    # 每节转角的如意小饰
    for s in (-1, 1):
        cv.circle(s * 25.8, z1 - 3.2, 1.1)
    z = z1
# 阶梯塔冠
for z0, z1, w in [(z, z + 16, 19), (z + 16, z + 30, 14.5), (z + 30, z + 44, 10.5), (z + 44, z + 54, 7)]:
    L([(-w, z0), (-w, z1), (w, z1), (w, z0)], OUTER)
    L([(-w, (z0 + z1) / 2), (w, (z0 + z1) / 2)])
top = z + 54
L([(-2.2, top), (-1.4, top + 30), (-0.5, 508 - 449 + 449 - (449 - top) * 0)], OUTER)
L([(2.2, top), (1.4, top + 30), (0.5, 508 - 449 + 449 - (449 - top) * 0)], OUTER)
L([(-0.5, 508), (0.5, 508)], OUTER)
L([(-1.4, top + 30), (1.4, top + 30)])
cv.save(sys.argv[1])
