"""05-liberty：自由女神像全身 + 花岗岩基座 + 星形堡垒底座。竖幅 1024x1536。
单位：米。地面 0，堡垒顶 7，基础顶 27，基座顶 47，火炬顶 93。
人物面向观者：她的右手（画面左侧）高举火炬，左臂（画面右侧）抱铭牌。
"""
import math
import sys
from lineart import Canvas, OUTER, INNER

cv = Canvas("竖", seed=5)
L, S = cv.line, cv.smooth

# ---------------- 星形堡垒 (0–7) ----------------
FW = 30.0
L([(-FW - 1.2, 0), (-FW, 6.2), (FW, 6.2), (FW + 1.2, 0)], OUTER)
L([(-FW - 2.5, 0), (FW + 2.5, 0)], OUTER)                    # 地面
L([(-FW, 7.0), (FW, 7.0)], INNER)                           # 胸墙
L([(-FW, 6.2), (-FW, 7.0)], INNER); L([(FW, 6.2), (FW, 7.0)], INNER)
for x in (-23, -12.5, 0, 12.5, 23):                         # 星角棱线
    L([(x * 1.02, 0.2), (x, 6.0)], INNER)

# ---------------- 阶梯式基础 (7–27) ----------------
steps = [(7.0, 12.0, 14.5, 13.8), (12.0, 18.5, 13.2, 12.5), (18.5, 25.0, 12.0, 11.3), (25.0, 27.0, 11.0, 11.0)]
for z0, z1, w0, w1 in steps:
    L([(-w0, z0), (-w1, z1)], OUTER); L([(w0, z0), (w1, z1)], OUTER)
    L([(-w1, z1), (w1, z1)], OUTER if z1 == 27.0 else INNER)
for z0, z1, w0, w1 in steps[:3]:
    L([(-w1, z1), (-w1 + 0.0, z1)], INNER)
# 台阶之间的退台小横线
for z, a, b in [(12.0, 13.8, 13.2), (18.5, 12.5, 12.0), (25.0, 11.3, 11.0)]:
    L([(-a, z), (-b, z)], OUTER); L([(a, z), (b, z)], OUTER)
# 入口
L([(-2.2, 7.0), (-2.2, 10.5), (2.2, 10.5), (2.2, 7.0)], INNER)

# ---------------- 花岗岩基座 (27–47) ----------------
# 底座台阶
L([(-10.2, 27.0), (-10.2, 29.0), (10.2, 29.0), (10.2, 27.0)], OUTER)
# 主体，略收分
L([(-9.4, 29.0), (-9.0, 41.5)], OUTER); L([(9.4, 29.0), (9.0, 41.5)], OUTER)
# 主体内的转角壁柱
L([(-7.0, 29.0), (-6.9, 41.5)], INNER); L([(7.0, 29.0), (6.9, 41.5)], INNER)
# 石材水平分层
for z in (31.0, 33.0):
    L([(-9.3, z), (9.3, z)], INNER)
# 下部拱门
S([(-1.6, 33.0), (-1.6, 36.2), (0, 37.6), (1.6, 36.2), (1.6, 33.0)], INNER, n=8)
# 敞廊：带檐口的框 + 4 根柱
L([(-9.1, 38.0), (9.1, 38.0)], INNER)
L([(-4.6, 38.0), (-4.6, 41.5)], INNER); L([(4.6, 38.0), (4.6, 41.5)], INNER)
for x in (-3.3, -1.1, 1.1, 3.3):
    L([(x, 38.0), (x, 41.0)], INNER)
L([(-4.6, 41.0), (4.6, 41.0)], INNER)
# 上部檐口 + 盾徽圆盘带
L([(-9.6, 41.5), (9.6, 41.5), (9.6, 42.3), (-9.6, 42.3), (-9.6, 41.5)], OUTER)
L([(-8.8, 42.3), (-8.8, 44.6)], OUTER); L([(8.8, 42.3), (8.8, 44.6)], OUTER)
for x in (-6.6, -3.3, 0.0, 3.3, 6.6):
    pts = [(x + 0.75 * math.cos(t / 16 * 2 * math.pi), 43.45 + 0.75 * math.sin(t / 16 * 2 * math.pi)) for t in range(16)]
    L(pts, INNER, closed=True)
# 顶部女儿墙
L([(-9.3, 44.6), (9.3, 44.6), (9.3, 45.4), (-9.3, 45.4), (-9.3, 44.6)], OUTER)
L([(-7.6, 45.4), (-7.6, 46.3), (7.6, 46.3), (7.6, 45.4)], OUTER)

# ---------------- 雕像 (46.3–93) ----------------
# 脚下小台
L([(-5.4, 46.3), (-5.4, 47.2), (5.4, 47.2), (5.4, 46.3)], OUTER)

# 身体左侧轮廓（画面左）：裙摆 → 腰 → 肩 → 高举手臂外缘 → 手
S([(-5.0, 47.2), (-4.75, 51), (-4.3, 57), (-3.95, 63), (-4.05, 68), (-4.35, 71.8),
   (-4.75, 75), (-5.3, 79), (-5.9, 83), (-6.35, 86.2)], OUTER, n=8)
# 手臂内缘 → 腋下 → 颈
S([(-4.85, 86.4), (-4.4, 83), (-3.75, 79.5), (-3.05, 76.6), (-2.2, 75.2), (-1.15, 75.4)], OUTER, n=8)
# 手（握火炬）
S([(-6.35, 86.2), (-6.5, 87.2), (-5.9, 87.9), (-5.0, 87.7), (-4.85, 86.4)], OUTER, n=6)
L([(-6.3, 86.9), (-4.95, 86.9)], INNER)
# 袖口垂褶
S([(-4.7, 81.0), (-5.6, 79.6), (-5.25, 78.0)], INNER, n=6)

# 火炬
TX = -5.7
L([(TX - 0.35, 87.9), (TX - 0.3, 89.3)], OUTER); L([(TX + 0.35, 87.9), (TX + 0.3, 89.3)], OUTER)
L([(TX - 0.8, 89.3), (TX - 1.55, 90.4), (TX + 1.55, 90.4), (TX + 0.8, 89.3), (TX - 0.8, 89.3)], OUTER)
L([(TX - 1.15, 89.85), (TX + 1.15, 89.85)], INNER)
S([(TX - 1.1, 90.4), (TX - 1.05, 91.4), (TX - 0.35, 92.3), (TX + 0.05, 93.0), (TX + 0.35, 92.1),
   (TX + 0.95, 91.6), (TX + 1.1, 90.4)], OUTER, n=6)
S([(TX - 0.35, 90.5), (TX - 0.25, 91.4), (TX + 0.15, 92.0)], INNER, n=5)

# 头
S([(-1.15, 75.4), (-1.35, 76.4), (-1.75, 77.6), (-1.7, 79.0), (-1.1, 80.0), (0, 80.35),
   (1.1, 80.0), (1.7, 79.0), (1.75, 77.6), (1.35, 76.4), (1.15, 75.4)], OUTER, n=6)
S([(-0.9, 76.2), (0, 75.75), (0.9, 76.2)], INNER, n=5)        # 下颌
# 冠冕：冠箍 + 七道光芒
S([(-1.75, 78.9), (-0.9, 79.25), (0, 79.35), (0.9, 79.25), (1.75, 78.9)], INNER, n=5)
S([(-1.85, 79.15), (-1.2, 80.15), (0, 80.6), (1.2, 80.15), (1.85, 79.15)], OUTER, n=5)
for k in range(7):
    a = math.radians(-78 + k * 26)             # 相对竖直方向的角度
    bx, bz = 1.55 * math.sin(a), 79.2 + 1.2 * math.cos(a)
    tx, tz = bx + 3.0 * math.sin(a), bz + 3.0 * math.cos(a)
    px, pz = 0.32 * math.cos(a), -0.32 * math.sin(a)
    L([(bx - px, bz - pz), (tx, tz), (bx + px, bz + pz)], OUTER)

# 身体右侧（画面右）：颈 → 左肩 → 抱铭牌的上臂
S([(1.15, 75.4), (2.3, 74.6), (3.6, 73.6), (4.4, 72.2), (5.0, 70.3), (5.4, 68.0), (5.6, 64.5), (5.64, 63.1)], OUTER, n=8)
# 铭牌（顶部向头部倾斜）
ang = math.radians(18)
ux, uz = -math.sin(ang), math.cos(ang)
vx, vz = math.cos(ang), math.sin(ang)
cxt, czt = 3.6, 64.5
hh, hw = 3.75, 1.45
corner = lambda a, b: (cxt + ux * hh * a + vx * hw * b, czt + uz * hh * a + vz * hw * b)
tab = [corner(1, -1), corner(1, 1), corner(-1, 1), corner(-1, -1)]
L(tab, OUTER, closed=True)
inset = [(cxt + ux * (hh - 0.5) * a + vx * (hw - 0.4) * b, czt + uz * (hh - 0.5) * a + vz * (hw - 0.4) * b)
         for a, b in ((1, -1), (1, 1), (-1, 1), (-1, -1))]
L(inset, INNER, closed=True)
# 身体右侧在铭牌下方继续到裙摆
S([(4.4, 60.95), (4.45, 58), (4.7, 54), (5.0, 50), (5.1, 47.2)], OUTER, n=8)

# 披肩斜褶：从左肩斜向右下
S([(-3.9, 72.0), (-1.5, 70.0), (0.4, 68.0), (1.5, 66.7)], INNER, n=8)
S([(-3.95, 69.0), (-1.6, 67.2), (0.4, 64.8), (2.2, 62.6)], INNER, n=8)
S([(-1.3, 74.6), (0.4, 72.6), (1.6, 70.6), (2.3, 69.0)], INNER, n=6)
# 长袍竖褶
for x0, x1 in [(-3.0, -3.4), (-1.5, -1.6), (0.0, 0.15), (1.5, 1.8), (3.0, 3.4)]:
    top = 66.5 - abs(x0) * 0.4 if x0 < 2 else 60.5
    S([(x0 * 0.8, top), (x0 * 0.95, (top + 47.6) / 2), (x1, 47.8)], INNER, n=8)
# 裙摆波浪边
S([(-5.0, 47.25), (-3.8, 47.7), (-2.4, 47.35), (-0.9, 47.75), (0.6, 47.35), (2.1, 47.75), (3.6, 47.35), (5.1, 47.25)],
  INNER, n=6)

cv.save(sys.argv[1])
